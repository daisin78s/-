"""Convert ストーリー.xlsx (story mode script) into data/story.data.js.

Usage: python tools/story_xlsx_to_js.py [path/to/ストーリー.xlsx]
Input, first found: the argument, data/story.xlsx, ~/Desktop/ストーリー.xlsx.
Output: data/story.data.js, a plain browser global (window.STORY_SCRIPT) loaded via a normal <script src>
tag -- same reasoning as data/game.data.js (index.html must keep working from file://).

Each row is keyed by its id in column A (S001, S002, ...) -- the sheet's own 移動先 columns already point at
these ids, so they are the stable name of a line. Exported per row: the セリフ text and the 選択肢/移動先
pairs. The other columns (光る/動く/スクロール/進む条件/他に置いたら/メモ) are instructions for Claude Code to
implement in story.js, not auto-loaded. Rows with an empty セリフ are skipped. Dev-time tool only.
"""
import json
import sys
from pathlib import Path

import openpyxl

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEST_JS = PROJECT_ROOT / "data" / "story.data.js"
CANDIDATES = [
    PROJECT_ROOT / "data" / "story.xlsx",
    Path.home() / "Desktop" / "ストーリー.xlsx",
]


def find_source():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    for path in CANDIDATES:
        if path.exists():
            return path
    raise SystemExit("ストーリー.xlsx が見つかりません: " + ", ".join(str(p) for p in CANDIDATES))


def clean_text(value):
    return str(value).replace("\r\n", "\n").replace("\r", "\n").strip(" \t\n")


def main():
    src = find_source()
    ws = openpyxl.load_workbook(src, data_only=True).worksheets[0]
    header = {ws.cell(1, c).value: c for c in range(1, ws.max_column + 1) if ws.cell(1, c).value}
    if "セリフ" not in header:
        raise SystemExit("セリフ列が見つかりません")
    script = {}
    for r in range(2, ws.max_row + 1):
        row_id = ws.cell(r, 1).value
        value = ws.cell(r, header["セリフ"]).value
        if not row_id or value is None or not clean_text(value):
            continue
        entry = {"text": clean_text(value)}
        choices = []
        for n in range(1, 7):
            label_col, dest_col = header.get(f"選択肢{n}"), header.get(f"移動先{n}")
            label = ws.cell(r, label_col).value if label_col else None
            if label is None or not clean_text(label):
                continue
            dest = ws.cell(r, dest_col).value if dest_col else None
            choices.append({"label": clean_text(label), "to": clean_text(dest) if dest else None})
        if choices:
            entry["choices"] = choices
        script[str(row_id).strip()] = entry
    body = json.dumps(script, ensure_ascii=False, indent=2)
    DEST_JS.write_text(
        "// Generated by tools/story_xlsx_to_js.py from ストーリー.xlsx -- do not edit by hand.\n"
        "window.STORY_SCRIPT = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"{len(script)} 行 <- {src}\n-> {DEST_JS}")


if __name__ == "__main__":
    main()
