"""Convert the Twine story (怠惰なローマ人アレク) into data/story.data.js.

Usage: python tools/story_twine_to_js.py [path/to/story.html]
Input, first found: the argument; otherwise the newest .html under ~/Documents/Twine/ストーリー or
~/Documents/Twine/Stories whose <tw-storydata name="..."> is STORY_NAME (Twine names its library folder in
the app's language, so both are checked).
Output: data/story.data.js, a plain browser global (window.STORY_SCRIPT) loaded via a normal <script src>
tag -- same reasoning as data/game.data.js (index.html must keep working from file://).

2026-10-27, per user: the story's lines and branches are now written in Twine instead of ストーリー.xlsx
("Twineを元にする"). Each passage is keyed by the S-number at the end of its name (Twine passage names look
like "次へ→S007" or "「農園」にダイスを置く→S006"); the start passage (no S-number in its name) is S001.
Exported per passage: the text (links [[...]] and macros like (live: 5s)[...] removed) and its links as
choices [{label, to}]. Instructions such as 光る/メモ still live in ストーリー.xlsx and are implemented by
hand in story.js. Dev-time tool only; the game never reads Twine files directly.
"""
import html
import json
import re
import sys
from pathlib import Path

STORY_NAME = "怠惰なローマ人アレク"
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DEST_JS = PROJECT_ROOT / "data" / "story.data.js"
LIBRARY_DIRS = [
    Path.home() / "Documents" / "Twine" / "ストーリー",
    Path.home() / "Documents" / "Twine" / "Stories",
]
ARROW = r"(?:→|->)"


def find_source():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    candidates = []
    for folder in LIBRARY_DIRS:
        if not folder.exists():
            continue
        for path in folder.glob("*.html"):
            text = path.read_text(encoding="utf-8", errors="ignore")
            if f'<tw-storydata name="{STORY_NAME}"' in text:
                candidates.append(path)
    if not candidates:
        raise SystemExit(f"Twineのストーリー「{STORY_NAME}」が見つかりません: " + ", ".join(str(p) for p in LIBRARY_DIRS))
    return max(candidates, key=lambda p: p.stat().st_mtime)


def passage_id(name, is_start):
    m = re.search(ARROW + r"\s*(S\d+)\s*$", name) or re.fullmatch(r"\s*(S\d+)\s*", name)
    if m:
        return m.group(1)
    return "S001" if is_start else None


def main():
    src = find_source()
    doc = src.read_text(encoding="utf-8")
    story = re.search(r"<tw-storydata[^>]*>", doc).group(0)
    start_pid = re.search(r'startnode="(\d+)"', story).group(1)
    script = {}
    for m in re.finditer(r'<tw-passagedata pid="(\d+)" name="([^"]*)"[^>]*>(.*?)</tw-passagedata>', doc, re.S):
        pid, name, body = m.group(1), html.unescape(m.group(2)), html.unescape(m.group(3))
        sid = passage_id(name, pid == start_pid)
        if not sid:
            print(f"注意: パッセージ「{name}」にS番号がないので読みませんでした")
            continue
        choices = []
        for link in re.findall(r"\[\[(.*?)\]\]", body):
            target = passage_id(link, False)
            if not target:
                continue
            # 行き先は末尾の「→S050」だけ(選択肢の文言自体に「A→K」のような矢印が入ることがあるため)。
            label = re.sub(ARROW + r"\s*S\d+\s*$", "", link).strip()
            choices.append({"label": label, "to": target})
        text = re.sub(r"\[\[.*?\]\]", "", body)
        text = re.sub(r"\(live:[^)]*\)\[[^\]]*\]", "", text)
        text = "\n".join(line.rstrip() for line in text.strip().splitlines()).strip()
        entry = {"text": text}
        if choices:
            entry["choices"] = choices
        if sid in script:
            print(f"注意: {sid} が複数のパッセージにあります(先のものを使います)")
            continue
        script[sid] = entry
    ordered = dict(sorted(script.items(), key=lambda kv: int(kv[0][1:])))
    body = json.dumps(ordered, ensure_ascii=False, indent=2)
    DEST_JS.write_text(
        "// Generated by tools/story_twine_to_js.py from the Twine story (" + STORY_NAME + ") -- do not edit by hand.\n"
        "window.STORY_SCRIPT = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"{len(ordered)} パッセージ <- {src}\n-> {DEST_JS}")


if __name__ == "__main__":
    main()
